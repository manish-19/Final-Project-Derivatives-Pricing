class OptionBacktester:
    """Backtest an OptionStrategy using historical price paths."""

    def __init__(self, prices: np.ndarray, strategy_builder: Callable, initial_capital: float = 100000.0):
        self.prices = prices
        self.strategy_builder = strategy_builder
        self.initial_capital = initial_capital
        self.daily_pnl: list[dict] = []

    def run(
        self,
        market_inputs: MarketInputs,
        option_contract: OptionContract,
        sigma: float,
    ) -> pd.DataFrame:
        for i in range(1, len(self.prices)):
            S_prev, S_curr = self.prices[i - 1], self.prices[i]
            dS = S_curr - S_prev

            val_prev = market_inputs.valuation_date + timedelta(days=i - 1)
            val_curr = market_inputs.valuation_date + timedelta(days=i)

            mi_prev = MarketInputs(S_prev, market_inputs.risk_free_rate, market_inputs.dividend_yield, val_prev)
            mi_curr = MarketInputs(S_curr, market_inputs.risk_free_rate, market_inputs.dividend_yield, val_curr)

            oc_prev = OptionContract(
                ticker=option_contract.ticker,
                option_type=option_contract.option_type,
                strike=option_contract.strike,
                expiry_date=option_contract.expiry_date,
                implied_volatility=sigma,
            )
            oc_curr = OptionContract(
                ticker=option_contract.ticker,
                option_type=option_contract.option_type,
                strike=option_contract.strike,
                expiry_date=option_contract.expiry_date,
                implied_volatility=sigma,
            )

            strat_prev = self.strategy_builder(mi_prev, oc_prev)
            greeks_prev = strat_prev.all_greeks()
            strat_curr = self.strategy_builder(mi_curr, oc_curr)
            greeks_curr = strat_curr.all_greeks()

            delta_pnl = greeks_prev["delta"] * dS
            gamma_pnl = 0.5 * greeks_prev["gamma"] * (dS ** 2)
            theta_pnl = greeks_prev["theta"] * (-1.0)
            total_pnl = greeks_curr["price"] - greeks_prev["price"]
            unexplained = total_pnl - (delta_pnl + gamma_pnl + theta_pnl)

            self.daily_pnl.append({
                "day": i,
                "S_prev": S_prev,
                "S_curr": S_curr,
                "dS": dS,
                "total_pnl": total_pnl,
                "delta_pnl": delta_pnl,
                "gamma_pnl": gamma_pnl,
                "theta_pnl": theta_pnl,
                "unexplained": unexplained,
            })

        df = pd.DataFrame(self.daily_pnl)
        df["cum_pnl"] = df["total_pnl"].cumsum()
        df["cum_delta_pnl"] = df["delta_pnl"].cumsum()
        df["cum_gamma_pnl"] = df["gamma_pnl"].cumsum()
        df["cum_theta_pnl"] = df["theta_pnl"].cumsum()
        return df

