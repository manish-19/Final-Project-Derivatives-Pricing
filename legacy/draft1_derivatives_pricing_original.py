def implied_volatility(
    market_price: float,
    market_inputs: MarketInputs,
    option_contract: OptionContract,
) -> float:
    """Solve for implied volatility using Brent's method."""

    def objective(sigma: float) -> float:
        try:
            contract = OptionContract(
                ticker=option_contract.ticker,
                option_type=option_contract.option_type,
                strike=option_contract.strike,
                expiry_date=option_contract.expiry_date,
                implied_volatility=sigma,
            )
            return BlackScholesMerton(market_inputs, contract).price() - market_price
        except Exception:
            return 1e10

    try:
        return float(brentq(objective, 0.001, 5.0, xtol=1e-8))
    except ValueError:
        return np.nan

def implied_q_one(g, S, r, T, band=0.10, min_pairs=5):
    """g: rows for a single (Date, expiry). Returns implied q or np.nan."""
    piv = g.pivot_table(index='strike', columns='option_type',
                        values='market_option_price', aggfunc='first')
    if not {'call', 'put'}.issubset(piv.columns):
        return np.nan
    # spread pivot for liquidity weighting, aligned to the same strikes
    spr = g.pivot_table(index='strike', columns='option_type',
                        values='bid_ask_spread', aggfunc='first')
    piv = piv.dropna(subset=['call', 'put'])
    piv = piv[(piv.index > (1 - band) * S) & (piv.index < (1 + band) * S)]
    if len(piv) < min_pairs:
        return np.nan
    K = piv.index.values.astype(float)
    y = (piv['call'] - piv['put']).values                 # = e^{-rT}(F - K)

    # liquidity weight: inverse combined call+put spread, guarded against 0
    s = spr.reindex(piv.index)[['call', 'put']].sum(axis=1).values
    w = 1.0 / np.clip(s, 1e-3, None)
    slope, intercept = np.polyfit(K, y, 1, w=np.sqrt(w))   # polyfit wants sqrt-weights

    if slope >= 0:                                         # must be ~ -e^{-rT} < 0
        return np.nan
    disc = -slope                                          # e^{-rT}
    F = intercept / disc                                   # forward
    if F <= 0:
        return np.nan
    if T * abs(np.log(F / S)) < 1e-4:                      # conditioning guard
        return np.nan                                     # q not identifiable; use fallback
    return r - np.log(F / S) / T

