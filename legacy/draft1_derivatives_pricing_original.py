    def test_greeks_finite_difference_consistency(self):
        """Verify Greeks are consistent with finite differences."""
        # Use BSM for analytical Greeks
        model = BlackScholesMerton(self.market_inputs, self.option_contract)

        # Delta: (P(S+h) - P(S-h)) / (2h)
        h = 0.01 * self.S
        mi_up = MarketInputs(self.S + h, self.r, self.q, self.valuation_date)
        mi_down = MarketInputs(self.S - h, self.r, self.q, self.valuation_date)

        price_up = BlackScholesMerton(mi_up, self.option_contract).price()
        price_down = BlackScholesMerton(mi_down, self.option_contract).price()
        fd_delta = (price_up - price_down) / (2 * h)

        # Analytical delta should match finite difference
        self.assertAlmostEqual(model.delta(), fd_delta, places=4)

