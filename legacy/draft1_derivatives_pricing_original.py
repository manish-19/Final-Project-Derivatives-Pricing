class BarrierOptionPDE(PricingModel):
    """Crank-Nicolson PDE for zero-rebate European single-barrier options."""
    def __init__(self,market_inputs,option_contract,barrier,barrier_type='up-and-out',M=280,N=280,smax_mult=4.0):
        super().__init__(market_inputs,option_contract); self.S=float(market_inputs.underlying_price); self.K=float(option_contract.strike); self.r=float(market_inputs.risk_free_rate); self.q=float(market_inputs.dividend_yield); self.T=year_fraction(market_inputs.valuation_date,option_contract.expiry_date); self.sigma=float(option_contract.implied_volatility if option_contract.implied_volatility is not None else .20)
        self.barrier=float(barrier); self.barrier_type=barrier_type.lower(); self.M=max(int(M),80); self.N=max(int(N),80); self.smax_mult=float(smax_mult)
        if self.barrier_type not in {'up-and-out','down-and-out','up-and-in','down-and-in'}: raise ValueError('invalid barrier_type')
    @property
    def direction(self): return 'up' if self.barrier_type.startswith('up') else 'down'
    @property
    def knock(self): return 'out' if self.barrier_type.endswith('out') else 'in'
    def _breached(self,S=None):
        S=self.S if S is None else S; return S>=self.barrier if self.direction=='up' else S<=self.barrier
    def _boundaries(self,tau,Smin,Smax):
        if self.direction=='up':
            left=0.0 if self.option_contract.option_type=='call' else self.K*math.exp(-self.r*tau) # S=0
            right=0.0
        else:
            left=0.0
            right=max(Smax*math.exp(-self.q*tau)-self.K*math.exp(-self.r*tau),0.0) if self.option_contract.option_type=='call' else 0.0
        return left,right
    def _knockout_price_grid(self,S0=None,r=None,q=None,sigma=None,T=None,return_grid=False):
        S0=self.S if S0 is None else float(S0); r0,q0,sig,T0=self.r if r is None else float(r),self.q if q is None else float(q),self.sigma if sigma is None else float(sigma),self.T if T is None else max(float(T),0)
        if T0<=0:
            vanilla=max(S0-self.K,0) if self.option_contract.option_type=='call' else max(self.K-S0,0); val=0.0 if self._breached(S0) else vanilla; return (val,None,None) if return_grid else val
        if (self.direction=='up' and S0>=self.barrier) or (self.direction=='down' and S0<=self.barrier): return (0.0,None,None) if return_grid else 0.0
        if self.direction=='up': Smin=0.0; Smax=self.barrier
        else: Smin=self.barrier; Smax=max(self.smax_mult*max(S0,self.K), self.barrier*1.05)
        grid=np.linspace(Smin,Smax,self.M+1); ds=grid[1]-grid[0]; dt=T0/self.N; s=grid[1:-1]
        V=np.maximum(s-self.K,0) if self.option_contract.option_type=='call' else np.maximum(self.K-s,0)
        a=0.5*sig**2*s**2/ds**2 - 0.5*(r0-q0)*s/ds
        b=-(sig**2*s**2/ds**2 + r0)
        c=0.5*sig**2*s**2/ds**2 + 0.5*(r0-q0)*s/ds
        lower=-0.5*dt*a[1:]; diag=1-0.5*dt*b; upper=-0.5*dt*c[:-1]
        ab=np.zeros((3,len(s))); ab[0,1:]=upper; ab[1,:]=diag; ab[2,:-1]=lower
        snapshots=[]
        for n in range(self.N):
            tau_old=n*dt; tau_new=(n+1)*dt
            # boundaries using local r0/q0 rather than self.r/q for scenario repricing
            if self.direction=='up':
                Lold=0.0 if self.option_contract.option_type=='call' else self.K*math.exp(-r0*tau_old); Lnew=0.0 if self.option_contract.option_type=='call' else self.K*math.exp(-r0*tau_new); Rold=Rnew=0.0
            else:
                Lold=Lnew=0.0
                if self.option_contract.option_type=='call':
                    Rold=max(Smax*math.exp(-q0*tau_old)-self.K*math.exp(-r0*tau_old),0); Rnew=max(Smax*math.exp(-q0*tau_new)-self.K*math.exp(-r0*tau_new),0)
                else: Rold=Rnew=0.0
            rhs=(1+0.5*dt*b)*V
            rhs[1:]+=0.5*dt*a[1:]*V[:-1]; rhs[:-1]+=0.5*dt*c[:-1]*V[1:]
            rhs[0]+=0.5*dt*a[0]*(Lold+Lnew); rhs[-1]+=0.5*dt*c[-1]*(Rold+Rnew)
            V=solve_banded((1,1),ab,rhs)
            if return_grid and (n in np.linspace(0,self.N-1,40,dtype=int)): snapshots.append(np.concatenate([[Lnew],V,[Rnew]]))
        val=float(np.interp(S0,grid,np.concatenate([[Lnew],V,[Rnew]])))
        if return_grid: return val,grid,np.array(snapshots)
        return val
    def _vanilla(self,S0=None,r=None,q=None,sigma=None,T=None):
        S0=self.S if S0 is None else float(S0); r0=self.r if r is None else float(r); q0=self.q if q is None else float(q); sig=self.sigma if sigma is None else float(sigma); T0=self.T if T is None else max(float(T),0)
        vd=self.market_inputs.valuation_date; exp=vd+timedelta(days=max(int(round(T0*365)),0)); mi=MarketInputs(S0,r0,q0,vd); oc=replace(self.option_contract,expiry_date=exp,implied_volatility=sig); return BlackScholesMerton(mi,oc).price()
    def _price_scenario(self,S=None,r=None,q=None,sigma=None,T=None):
        S0=self.S if S is None else float(S); ko=self._knockout_price_grid(S0=S0,r=r,q=q,sigma=sigma,T=T)
        if self.knock=='out': return ko
        if (self.direction=='up' and S0>=self.barrier) or (self.direction=='down' and S0<=self.barrier): return self._vanilla(S0=S0,r=r,q=q,sigma=sigma,T=T)
        return max(self._vanilla(S0=S0,r=r,q=q,sigma=sigma,T=T)-ko,0.0)
    def price(self): return self._price_scenario()
    def delta(self):
        h=max(.005*self.S,.02); return (self._price_scenario(S=self.S+h)-self._price_scenario(S=max(self.S-h,1e-8)))/(2*h)
    def gamma(self):
        h=max(.01*self.S,.05); return (self._price_scenario(S=self.S+h)-2*self.price()+self._price_scenario(S=max(self.S-h,1e-8)))/h**2
    def vega(self):
        h=.01; hi=self.sigma+h; lo=max(self.sigma-h,1e-6); return (self._price_scenario(sigma=hi)-self._price_scenario(sigma=lo))/(hi-lo)/100
    def theta(self):
        if self.T<=1/365:return np.nan
        return self._price_scenario(T=self.T-1/365)-self.price()
    def rho(self):
        h=.0005; return (self._price_scenario(r=self.r+h)-self._price_scenario(r=self.r-h))/(2*h)/100
    def price_grid(self): return self._knockout_price_grid(return_grid=True)
    def barrier_sensitivity(self,levels):
        rows=[]; orig=self.barrier
        for h in levels:
            self.barrier=float(h); rows.append({'barrier':float(h),'price':self.price()})
        self.barrier=orig; return pd.DataFrame(rows)

