    def test_monte_carlo_convergence(self):
        """Monte Carlo should converge to BSM as paths increase."""
        bsm_price = BlackScholesMerton(self.market_inputs, self.option_contract).price()

        # Create Asian option with averaging over all steps (effectively European)
        # For a vanilla option, Asian with one step is just vanilla
