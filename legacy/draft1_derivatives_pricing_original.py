def generate_bsm_call_heatmaps(
    market_inputs,
    option_contract,
    output_path,
    spot_range=None,
    volatility_range=(0.10, 0.60),
    grid_size=70,
):
    """
    Generate BSM call price and Greek heatmaps.

    The heatmaps vary:

        1. Underlying spot price
        2. Implied volatility

    The following inputs remain fixed:

        - Strike
        - Expiry
        - Risk-free rate
        - Dividend yield

    Greek units follow the existing BlackScholesMerton implementation:

        - Vega: change in value for a one-percentage-point volatility change
        - Theta: change in value per calendar day
        - Rho: change in value for a one-percentage-point rate change
    """

    strike = float(option_contract.strike)
    current_spot = float(market_inputs.underlying_price)
    current_volatility = float(
        option_contract.implied_volatility or 0.20
    )

    if spot_range is None:
        spot_range = (
            0.70 * strike,
            1.30 * strike,
        )

    spot_min, spot_max = spot_range
    volatility_min, volatility_max = volatility_range

    if spot_min <= 0 or spot_max <= spot_min:
        raise ValueError(
            "spot_range must contain positive, increasing values."
        )

    if volatility_min <= 0 or volatility_max <= volatility_min:
        raise ValueError(
            "volatility_range must contain positive, increasing values."
        )

    if grid_size < 10:
        raise ValueError("grid_size must be at least 10.")

    spot_values = np.linspace(
        spot_min,
        spot_max,
        grid_size,
    )

    volatility_values = np.linspace(
        volatility_min,
        volatility_max,
        grid_size,
    )

    spot_grid, volatility_grid = np.meshgrid(
        spot_values,
        volatility_values,
    )

    surfaces = {
        "Price": np.empty_like(spot_grid, dtype=float),
        "Delta": np.empty_like(spot_grid, dtype=float),
        "Gamma": np.empty_like(spot_grid, dtype=float),
        "Vega": np.empty_like(spot_grid, dtype=float),
        "Theta": np.empty_like(spot_grid, dtype=float),
        "Rho": np.empty_like(spot_grid, dtype=float),
    }

    # -------------------------------------------------------------------------
    # Evaluate the existing BSM model at each grid point
    # -------------------------------------------------------------------------

    for row in range(grid_size):
        for column in range(grid_size):
            scenario_market = MarketInputs(
                underlying_price=float(
                    spot_grid[row, column]
                ),
                risk_free_rate=market_inputs.risk_free_rate,
                dividend_yield=market_inputs.dividend_yield,
                valuation_date=market_inputs.valuation_date,
            )

            scenario_contract = OptionContract(
                ticker=option_contract.ticker,
                option_type="call",
                strike=strike,
                expiry_date=option_contract.expiry_date,
                implied_volatility=float(
                    volatility_grid[row, column]
                ),
            )

            model = BlackScholesMerton(
                scenario_market,
                scenario_contract,
            )

            surfaces["Price"][row, column] = model.price()
            surfaces["Delta"][row, column] = model.delta()
            surfaces["Gamma"][row, column] = model.gamma()
            surfaces["Vega"][row, column] = model.vega()
            surfaces["Theta"][row, column] = model.theta()
            surfaces["Rho"][row, column] = model.rho()

    # -------------------------------------------------------------------------
    # Heatmap formatting
    # -------------------------------------------------------------------------

    heatmap_settings = {
        "Price": {
            "title": "Call Price Surface",
            "label": "Option Value ($)",
            "cmap": "Blues",
        },
        "Delta": {
            "title": "Call Delta Surface",
            "label": "Delta",
            "cmap": "viridis",
        },
        "Gamma": {
            "title": "Call Gamma Surface",
            "label": "Gamma",
            "cmap": "Purples",
        },
        "Vega": {
            "title": "Call Vega Surface",
            "label": "Vega ($ per 1 vol point)",
            "cmap": "YlGnBu",
        },
        "Theta": {
            "title": "Call Theta Surface",
            "label": "Theta ($ per day)",
            "cmap": "coolwarm",
        },
        "Rho": {
            "title": "Call Rho Surface",
            "label": "Rho ($ per 1 rate point)",
            "cmap": "magma",
        },
    }

    figure, axes = plt.subplots(
        2,
        3,
        figsize=(19, 10.5),
        constrained_layout=True,
    )

    for axis, greek_name in zip(
        axes.flat,
        surfaces.keys(),
    ):
        settings = heatmap_settings[greek_name]
        values = surfaces[greek_name]

        contour = axis.contourf(
            spot_grid,
            volatility_grid,
            values,
            levels=25,
            cmap=settings["cmap"],
        )

        colorbar = figure.colorbar(
            contour,
            ax=axis,
            pad=0.02,
        )

        colorbar.set_label(
            settings["label"],
            fontsize=9,
        )

        # Strike line
        axis.axvline(
            strike,
            color="white",
            linestyle="--",
            linewidth=1.3,
            alpha=0.9,
            label="Strike",
        )

        # Current market point
        if (
            spot_min <= current_spot <= spot_max
            and volatility_min
            <= current_volatility
            <= volatility_max
        ):
            axis.scatter(
                current_spot,
                current_volatility,
                color="red",
                edgecolor="white",
                linewidth=0.8,
                s=45,
                zorder=5,
                label="Current market",
            )

        axis.set_title(
            settings["title"],
            fontsize=11,
            fontweight="bold",
        )

        axis.set_xlabel("Spot Price ($)")
        axis.set_ylabel("Implied Volatility")
        axis.grid(False)

    time_to_expiry = max(
        (
            option_contract.expiry_date
            - market_inputs.valuation_date
        ).days / 365.0,
        0.0,
    )

    figure.suptitle(
        "Black-Scholes-Merton Call Price and Greek Heatmaps\n"
        f"K=${strike:.2f} | "
        f"T={time_to_expiry:.4f} years | "
        f"r={market_inputs.risk_free_rate:.2%} | "
        f"q={market_inputs.dividend_yield:.2%}",
        fontsize=15,
        fontweight="bold",
    )

    output_path = Path(output_path)
    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    figure.savefig(
        output_path,
        dpi=180,
        bbox_inches="tight",
        facecolor="white",
    )

    plt.close(figure)

    print(
        f"BSM call heatmaps generated successfully: "
        f"{output_path}"
    )

    return surfaces


