# PHASE 3C — BARRIER OPTIONS: MONTE CARLO WITH BROWNIAN-BRIDGE CORRECTION
# =============================================================================
# plot_barrier_analysis() below compares the PDE price against a Monte Carlo
# price labelled "MC + Brownian bridge" -- this is that model. Raw discrete
# path monitoring understates the knock probability (a path can spike through
# the barrier *between* two simulated dates without being detected), so
# instead of a binary touch test we multiply each path's payoff by the exact
# probability that a Brownian bridge between two known log-price endpoints
# never crosses the barrier (Broadie-Glasserman-Kou 1997). This is unbiased
# for continuous monitoring even with a modest number of time steps.

class BarrierOptionMonteCarlo(MonteCarloOptionModel):
    """Zero-rebate single-barrier option via Monte Carlo with a Brownian-bridge
    continuity correction. Mirrors BarrierOptionPDE's interface (barrier,
    barrier_type, barrier_sensitivity) so the two can be plotted side by side."""
    def __init__(self,market_inputs,option_contract,barrier,barrier_type='up-and-out',n_paths=50_000,n_steps=252,seed=42,antithetic=True):
        super().__init__(market_inputs,option_contract,n_paths=n_paths,n_steps=n_steps,seed=seed,antithetic=antithetic)
        self.barrier=float(barrier); self.barrier_type=barrier_type.lower()
        if self.barrier_type not in {'up-and-out','down-and-out','up-and-in','down-and-in'}: raise ValueError('invalid barrier_type')
    @property
    def direction(self): return 'up' if self.barrier_type.startswith('up') else 'down'
    @property
    def knock(self): return 'out' if self.barrier_type.endswith('out') else 'in'
    def _survival_probabilities(self,paths,sigma,T):
        """Per-path probability of never touching the barrier, via Brownian-bridge crossing probabilities."""
        n_steps=paths.shape[1]-1; dt=T/n_steps; H=self.barrier
        logS=np.log(np.clip(paths,1e-12,None)); x0,x1=logS[:,:-1],logS[:,1:]; b=math.log(H)
        if self.direction=='up':
            already=(paths[:,:-1]>=H)|(paths[:,1:]>=H); gap=(b-x0)*(b-x1)
        else:
            already=(paths[:,:-1]<=H)|(paths[:,1:]<=H); gap=(x0-b)*(x1-b)
        gap=np.clip(gap,0.0,None)
        cross_prob=np.where(already,1.0,np.exp(-2.0*gap/(sigma**2*dt)))
        survive_step=np.clip(1.0-cross_prob,0.0,1.0)
        return np.prod(survive_step,axis=1)
    def _barrier_payoff(self,paths,sigma,T):
        terminal=paths[:,-1]
        vanilla=np.maximum(terminal-self.K,0.0) if self.option_contract.option_type=='call' else np.maximum(self.K-terminal,0.0)
        survive=self._survival_probabilities(paths,sigma,T)
        return vanilla*survive if self.knock=='out' else vanilla*(1.0-survive)
    def _payoff(self,paths):
        # used by standard_error()/confidence_interval()/simulation_summary() (base-case sigma/T only)
        return self._barrier_payoff(paths,self.sigma,self.T)
    def _price_scenario(self,S=None,r=None,q=None,sigma=None,T=None,z=None):
        r_used=self.r if r is None else float(r); T_used=self.T if T is None else max(float(T),1e-10); sig=self.sigma if sigma is None else float(sigma)
        paths=self._simulate_paths(S=S,r=r,q=q,sigma=sig,T=T_used,z=z)
        payoff=self._barrier_payoff(paths,sig,T_used)
        return float(np.exp(-r_used*T_used)*np.mean(payoff))
    def price(self):
        z=self._normal_draws(); return self._price_scenario(z=z)
    def barrier_sensitivity(self,levels):
        rows=[]; orig=self.barrier
        for h in levels:
            self.barrier=float(h); rows.append({'barrier':float(h),'price':self.price()})
        self.barrier=orig; return pd.DataFrame(rows)

