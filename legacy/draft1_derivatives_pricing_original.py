class MonteCarloOptionModel(PricingModel):
    """
    Base Monte Carlo pricing model.

    Provides:
    - GBM path simulation
    - Antithetic variance reduction
    - Monte Carlo standard error / confidence interval
    - Finite-difference Greeks using common random numbers
    """

    def __init__(
        self,
        market_inputs: MarketInputs,
        option_contract: OptionContract,
        n_paths: int = 50_000,
        n_steps: int = 252,
        seed: int = 42,
        antithetic: bool = True,
    ) -> None:
        super().__init__(market_inputs, option_contract)

        self.S = float(market_inputs.underlying_price)
        self.K = float(option_contract.strike)
        self.r = float(market_inputs.risk_free_rate)
        self.q = float(market_inputs.dividend_yield)

        self.T = max(
            (option_contract.expiry_date - market_inputs.valuation_date).days / 365.0,
            1e-10,
        )

        self.sigma = (
            float(option_contract.implied_volatility)
            if option_contract.implied_volatility is not None
            else 0.20
        )

        self.n_paths = int(n_paths)
        self.n_steps = int(n_steps)
        self.seed = int(seed)
        self.antithetic = bool(antithetic)

        if self.n_paths < 2:
            raise ValueError("n_paths must be at least 2.")

        if self.n_steps < 1:
            raise ValueError("n_steps must be at least 1.")

        if self.S <= 0:
            raise ValueError("Underlying price must be positive.")

        if self.K <= 0:
            raise ValueError("Strike must be positive.")

        if self.sigma <= 0:
            raise ValueError("Volatility must be positive.")

        if self.option_contract.option_type not in {"call", "put"}:
            raise ValueError("option_type must be 'call' or 'put'.")

    # -------------------------------------------------------------------------
    # RANDOM NUMBERS
    # -------------------------------------------------------------------------

    def _normal_draws(
        self,
        n_paths: int | None = None,
        n_steps: int | None = None,
    ) -> np.ndarray:

        n_paths = self.n_paths if n_paths is None else int(n_paths)
        n_steps = self.n_steps if n_steps is None else int(n_steps)

        rng = np.random.default_rng(self.seed)

        if self.antithetic:
            half_paths = (n_paths + 1) // 2

            z_half = rng.standard_normal(
                size=(half_paths, n_steps)
            )

            z = np.vstack([
                z_half,
                -z_half,
            ])

            return z[:n_paths]

        return rng.standard_normal(
            size=(n_paths, n_steps)
        )

    # -------------------------------------------------------------------------
    # GBM PATH SIMULATION
    # -------------------------------------------------------------------------

    def _simulate_paths(
        self,
        S: float | None = None,
        r: float | None = None,
        q: float | None = None,
        sigma: float | None = None,
        T: float | None = None,
        z: np.ndarray | None = None,
    ) -> np.ndarray:

        S = self.S if S is None else float(S)
        r = self.r if r is None else float(r)
        q = self.q if q is None else float(q)
        sigma = self.sigma if sigma is None else float(sigma)
        T = self.T if T is None else max(float(T), 1e-10)

        if z is None:
            z = self._normal_draws()

        n_paths, n_steps = z.shape

        dt = T / n_steps

        drift = (
            r
            - q
            - 0.5 * sigma ** 2
        ) * dt

        diffusion = (
            sigma
            * np.sqrt(dt)
            * z
        )

        log_returns = drift + diffusion

        log_paths = np.cumsum(
            log_returns,
            axis=1,
        )

        paths = np.empty(
            (n_paths, n_steps + 1),
            dtype=float,
        )

        paths[:, 0] = S

        paths[:, 1:] = (
            S
            * np.exp(log_paths)
        )

        return paths

    # -------------------------------------------------------------------------
    # PRODUCT-SPECIFIC PAYOFF
    # -------------------------------------------------------------------------

    def _payoff(
        self,
        paths: np.ndarray,
    ) -> np.ndarray:
        """
        Must be implemented by child classes.
        """
        raise NotImplementedError

    # -------------------------------------------------------------------------
    # MONTE CARLO PRICING
    # -------------------------------------------------------------------------

    def _discounted_payoffs(
        self,
        S: float | None = None,
        r: float | None = None,
        q: float | None = None,
        sigma: float | None = None,
        T: float | None = None,
        z: np.ndarray | None = None,
    ) -> np.ndarray:

        r_used = self.r if r is None else float(r)
        T_used = self.T if T is None else max(float(T), 1e-10)

        paths = self._simulate_paths(
            S=S,
            r=r,
            q=q,
            sigma=sigma,
            T=T_used,
            z=z,
        )

        payoff = self._payoff(paths)

        return (
            np.exp(-r_used * T_used)
            * payoff
        )

    def _price_scenario(
        self,
        S: float | None = None,
        r: float | None = None,
        q: float | None = None,
        sigma: float | None = None,
        T: float | None = None,
        z: np.ndarray | None = None,
    ) -> float:

        discounted_payoffs = self._discounted_payoffs(
            S=S,
            r=r,
            q=q,
            sigma=sigma,
            T=T,
            z=z,
        )

        return float(
            np.mean(discounted_payoffs)
        )

    def price(self) -> float:
        z = self._normal_draws()

        return self._price_scenario(
            z=z
        )

    # -------------------------------------------------------------------------
    # CONFIDENCE INTERVAL
    # -------------------------------------------------------------------------

    def standard_error(self) -> float:

        z = self._normal_draws()

        discounted_payoffs = self._discounted_payoffs(
            z=z
        )

        return float(
            np.std(
                discounted_payoffs,
                ddof=1,
            )
            / np.sqrt(len(discounted_payoffs))
        )

    def confidence_interval(
        self,
        confidence: float = 0.95,
    ) -> tuple[float, float]:

        if not 0.0 < confidence < 1.0:
            raise ValueError(
                "confidence must lie between 0 and 1."
            )

        z = self._normal_draws()

        discounted_payoffs = self._discounted_payoffs(
            z=z
        )

        price = float(
            np.mean(discounted_payoffs)
        )

        se = float(
            np.std(
                discounted_payoffs,
                ddof=1,
            )
            / np.sqrt(len(discounted_payoffs))
        )

        z_score = norm.ppf(
            0.5 + confidence / 2.0
        )

        lower = price - z_score * se
        upper = price + z_score * se

        return float(lower), float(upper)

    # -------------------------------------------------------------------------
    # FINITE-DIFFERENCE GREEKS
    #
    # Common Random Numbers:
    # Every bumped scenario uses exactly the same random draws.
    # This substantially reduces Monte Carlo noise in Greeks.
    # -------------------------------------------------------------------------

    def delta(self) -> float:

        h = max(
            0.01 * self.S,
            0.01,
        )

        z = self._normal_draws()

        price_up = self._price_scenario(
            S=self.S + h,
            z=z,
        )

        price_down = self._price_scenario(
            S=max(self.S - h, 1e-8),
            z=z,
        )

        return float(
            (price_up - price_down)
            / (2.0 * h)
        )

    def gamma(self) -> float:

        h = max(
            0.01 * self.S,
            0.01,
        )

        z = self._normal_draws()

        price_up = self._price_scenario(
            S=self.S + h,
            z=z,
        )

        price_base = self._price_scenario(
            S=self.S,
            z=z,
        )

        price_down = self._price_scenario(
            S=max(self.S - h, 1e-8),
            z=z,
        )

        return float(
            (
                price_up
                - 2.0 * price_base
                + price_down
            )
            / (h ** 2)
        )

    def vega(self) -> float:
        """
        Vega per 1 volatility point,
        consistent with the /100 convention
        used by your other models.
        """

        bump = 0.01

        z = self._normal_draws()

        sigma_up = self.sigma + bump

        sigma_down = max(
            self.sigma - bump,
            1e-8,
        )

        price_up = self._price_scenario(
            sigma=sigma_up,
            z=z,
        )

        price_down = self._price_scenario(
            sigma=sigma_down,
            z=z,
        )

        derivative = (
            price_up - price_down
        ) / (
            sigma_up - sigma_down
        )

        return float(
            derivative / 100.0
        )

    def rho(self) -> float:
        """
        Rho per 1 percentage-point change in rates.
        """

        bump = 0.0001

        z = self._normal_draws()

        price_up = self._price_scenario(
            r=self.r + bump,
            z=z,
        )

        price_down = self._price_scenario(
            r=self.r - bump,
            z=z,
        )

        derivative = (
            price_up - price_down
        ) / (
            2.0 * bump
        )

        return float(
            derivative / 100.0
        )

    def theta(self) -> float:
        """
        One-calendar-day theta.

        Positive result means the option gains value as one day passes;
        negative result means time decay reduces value.
        """

        one_day = 1.0 / 365.0

        if self.T <= one_day:
            return 0.0

        z = self._normal_draws()

        current_price = self._price_scenario(
            T=self.T,
            z=z,
        )

        tomorrow_price = self._price_scenario(
            T=self.T - one_day,
            z=z,
        )

        return float(
            tomorrow_price - current_price
        )

    # -------------------------------------------------------------------------
    # SIMULATION OUTPUT
    # -------------------------------------------------------------------------

    def simulation_summary(
        self,
    ) -> dict[str, float]:

        ci_low, ci_high = self.confidence_interval()

        return {
            "price": self.price(),
            "standard_error": self.standard_error(),
            "ci_95_lower": ci_low,
            "ci_95_upper": ci_high,
            "delta": self.delta(),
            "gamma": self.gamma(),
            "vega": self.vega(),
            "theta": self.theta(),
            "rho": self.rho(),
        }


# =============================================================================
# ASIAN OPTION — ARITHMETIC AVERAGE
# =============================================================================

class AsianOptionMonteCarlo(MonteCarloOptionModel):
    """
    Arithmetic-average Asian option.

    Payoff:
        Call: max(Average(S_t) - K, 0)
        Put : max(K - Average(S_t), 0)

    The initial spot S0 is excluded from the averaging convention here.
    """

    def _payoff(
        self,
        paths: np.ndarray,
    ) -> np.ndarray:

        average_price = np.mean(
            paths[:, 1:],
            axis=1,
        )

        if self.option_contract.option_type == "call":
            return np.maximum(
                average_price - self.K,
                0.0,
            )

        return np.maximum(
            self.K - average_price,
            0.0,
        )


# =============================================================================
# LOOKBACK OPTION — FLOATING STRIKE
# =============================================================================

class LookbackOptionMonteCarlo(MonteCarloOptionModel):
    """
    Floating-strike lookback option.

    Call:
        S_T - min(S_t)

    Put:
        max(S_t) - S_T
    """

    def _payoff(
        self,
        paths: np.ndarray,
    ) -> np.ndarray:

        terminal_price = paths[:, -1]

        if self.option_contract.option_type == "call":

            path_minimum = np.min(
                paths,
                axis=1,
            )

            return np.maximum(
                terminal_price - path_minimum,
                0.0,
            )

        path_maximum = np.max(
            paths,
            axis=1,
        )

        return np.maximum(
            path_maximum - terminal_price,
            0.0,
        )


