    error_df = pd.DataFrame({"N": step_grid, "crr_abs_error": crr_error, "lr_abs_error": lr_error})

    fig, ax = plt.subplots(figsize=(9, 6))
    ax.plot(step_grid, crr_error, "bo-", label="CRR |error|")
    ax.plot(step_grid, lr_error, "rs-", label="LR |error|")
    ax.set_yscale("log")
    ax.set_xlabel("Number of Steps (N)")
    ax.set_ylabel("Absolute Pricing Error vs BSM ($, log scale)")
    ax.set_title("Pricing Error vs Number of Steps")
    ax.legend()
    ax.grid(True, which="both", alpha=0.3)
    Path(output_path).parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output_path, dpi=150, bbox_inches="tight")
    plt.close(fig)
    return error_df, output_path


