# BASKET OPTION — MULTI-ASSET MONTE CARLO
# =============================================================================

class BasketOptionMonteCarlo(PricingModel):
    """
    European-style basket option on multiple correlated assets.

    Basket value:
        B_t = sum_i w_i S_i,t

    Payoff:
        Call: max(B_T - K, 0)
        Put : max(K - B_T, 0)
    """

    def __init__(
        self,
        market_inputs: MarketInputs,
        option_contract: OptionContract,
        asset_prices: list[float] | np.ndarray,
        volatilities: list[float] | np.ndarray,
        weights: list[float] | np.ndarray | None = None,
        correlation_matrix: np.ndarray | None = None,
        dividend_yields: list[float] | np.ndarray | None = None,
        n_paths: int = 50_000,
        seed: int = 42,
        antithetic: bool = True,
    ) -> None:

        super().__init__(
            market_inputs,
            option_contract,
        )

        self.asset_prices = np.asarray(
            asset_prices,
            dtype=float,
        )

        self.volatilities = np.asarray(
            volatilities,
            dtype=float,
        )

        self.n_assets = len(
            self.asset_prices
        )

        if len(self.volatilities) != self.n_assets:
            raise ValueError(
                "volatilities must have the same length as asset_prices."
            )

        if np.any(self.asset_prices <= 0):
            raise ValueError(
                "All asset prices must be positive."
            )

        if np.any(self.volatilities <= 0):
            raise ValueError(
                "All volatilities must be positive."
            )

        if weights is None:
            self.weights = np.full(
                self.n_assets,
                1.0 / self.n_assets,
            )
        else:
            self.weights = np.asarray(
                weights,
                dtype=float,
            )

            if len(self.weights) != self.n_assets:
                raise ValueError(
                    "weights must have the same length as asset_prices."
                )

            if np.isclose(
                np.sum(self.weights),
                0.0,
            ):
                raise ValueError(
                    "Basket weights cannot sum to zero."
                )

            self.weights = (
                self.weights
                / np.sum(self.weights)
            )

        if dividend_yields is None:
            self.dividend_yields = np.full(
                self.n_assets,
                float(market_inputs.dividend_yield),
            )
        else:
            self.dividend_yields = np.asarray(
                dividend_yields,
                dtype=float,
            )

            if len(self.dividend_yields) != self.n_assets:
                raise ValueError(
                    "dividend_yields must have the same length as asset_prices."
                )

        if correlation_matrix is None:
            self.correlation_matrix = np.eye(
                self.n_assets
            )
        else:
            self.correlation_matrix = np.asarray(
                correlation_matrix,
                dtype=float,
            )

        expected_shape = (
            self.n_assets,
            self.n_assets,
        )

        if self.correlation_matrix.shape != expected_shape:
            raise ValueError(
                f"correlation_matrix must have shape {expected_shape}."
            )

        if not np.allclose(
            self.correlation_matrix,
            self.correlation_matrix.T,
            atol=1e-10,
        ):
            raise ValueError(
                "correlation_matrix must be symmetric."
            )

        eigenvalues = np.linalg.eigvalsh(
            self.correlation_matrix
        )

        if np.min(eigenvalues) < -1e-10:
            raise ValueError(
                "correlation_matrix must be positive semidefinite."
            )

        # Small numerical stabilization for Cholesky
        self.cholesky = np.linalg.cholesky(
            self.correlation_matrix
            + 1e-12 * np.eye(self.n_assets)
        )

        self.K = float(
            option_contract.strike
        )

        self.r = float(
            market_inputs.risk_free_rate
        )

        self.T = max(
            (
                option_contract.expiry_date
                - market_inputs.valuation_date
            ).days / 365.0,
            1e-10,
        )

        self.n_paths = int(n_paths)
        self.seed = int(seed)
        self.antithetic = bool(antithetic)

        if option_contract.option_type not in {
            "call",
            "put",
        }:
            raise ValueError(
                "option_type must be 'call' or 'put'."
            )

    # -------------------------------------------------------------------------
    # CORRELATED TERMINAL PRICES
    # -------------------------------------------------------------------------

    def _normal_draws(
        self,
    ) -> np.ndarray:

        rng = np.random.default_rng(
            self.seed
        )

        if self.antithetic:

            half_paths = (
                self.n_paths + 1
            ) // 2

            z_half = rng.standard_normal(
                size=(
                    half_paths,
                    self.n_assets,
                )
            )

            z = np.vstack([
                z_half,
                -z_half,
            ])

            return z[:self.n_paths]

        return rng.standard_normal(
            size=(
                self.n_paths,
                self.n_assets,
            )
        )

    def _price_scenario(
        self,
        asset_prices: np.ndarray | None = None,
        volatilities: np.ndarray | None = None,
        r: float | None = None,
        T: float | None = None,
        correlation_matrix: np.ndarray | None = None,
        z: np.ndarray | None = None,
    ) -> float:

        prices = (
            self.asset_prices
            if asset_prices is None
            else np.asarray(
                asset_prices,
                dtype=float,
            )
        )

        vols = (
            self.volatilities
            if volatilities is None
            else np.asarray(
                volatilities,
                dtype=float,
            )
        )

        r_used = (
            self.r
            if r is None
            else float(r)
        )

        T_used = (
            self.T
            if T is None
            else max(float(T), 1e-10)
        )

        if z is None:
            z = self._normal_draws()

        if correlation_matrix is None:
            chol = self.cholesky
        else:
            corr = np.asarray(
                correlation_matrix,
                dtype=float,
            )

            chol = np.linalg.cholesky(
                corr
                + 1e-12 * np.eye(
                    self.n_assets
                )
            )

        correlated_z = (
            z @ chol.T
        )

        drift = (
            (
                r_used
                - self.dividend_yields
                - 0.5 * vols ** 2
            )
            * T_used
        )

        diffusion = (
            vols
            * np.sqrt(T_used)
            * correlated_z
        )

        terminal_prices = (
            prices
            * np.exp(
                drift
                + diffusion
            )
        )

        basket_terminal = (
            terminal_prices
            @ self.weights
        )

        if self.option_contract.option_type == "call":

            payoff = np.maximum(
                basket_terminal - self.K,
                0.0,
            )

        else:

            payoff = np.maximum(
                self.K - basket_terminal,
                0.0,
            )

        return float(
            np.exp(-r_used * T_used)
            * np.mean(payoff)
        )

    def price(self) -> float:

        z = self._normal_draws()

        return self._price_scenario(
            z=z
        )

    # -------------------------------------------------------------------------
    # BASKET GREEKS
    #
    # Spot Greeks shock all basket constituents proportionally.
    # -------------------------------------------------------------------------

    def delta(self) -> float:

        bump_pct = 0.01

        z = self._normal_draws()

        price_up = self._price_scenario(
            asset_prices=(
                self.asset_prices
                * (1.0 + bump_pct)
            ),
            z=z,
        )

        price_down = self._price_scenario(
            asset_prices=(
                self.asset_prices
                * (1.0 - bump_pct)
            ),
            z=z,
        )

        basket_spot = float(
            self.asset_prices
            @ self.weights
        )

        h = basket_spot * bump_pct

        return float(
            (price_up - price_down)
            / (2.0 * h)
        )

    def gamma(self) -> float:

        bump_pct = 0.01

        z = self._normal_draws()

        base_price = self._price_scenario(
            z=z
        )

        price_up = self._price_scenario(
            asset_prices=(
                self.asset_prices
                * (1.0 + bump_pct)
            ),
            z=z,
        )

        price_down = self._price_scenario(
            asset_prices=(
                self.asset_prices
                * (1.0 - bump_pct)
            ),
            z=z,
        )

        basket_spot = float(
            self.asset_prices
            @ self.weights
        )

        h = basket_spot * bump_pct

        return float(
            (
                price_up
                - 2.0 * base_price
                + price_down
            )
            / (h ** 2)
        )

    def vega(self) -> float:

        bump = 0.01

        z = self._normal_draws()

        price_up = self._price_scenario(
            volatilities=(
                self.volatilities
                + bump
            ),
            z=z,
        )

        price_down = self._price_scenario(
            volatilities=np.maximum(
                self.volatilities
                - bump,
                1e-8,
            ),
            z=z,
        )

        derivative = (
            price_up - price_down
        ) / (
            2.0 * bump
        )

        return float(
            derivative / 100.0
        )

    def theta(self) -> float:

        one_day = 1.0 / 365.0

        if self.T <= one_day:
            return 0.0

        z = self._normal_draws()

        current = self._price_scenario(
            T=self.T,
            z=z,
        )

        tomorrow = self._price_scenario(
            T=self.T - one_day,
            z=z,
        )

        return float(
            tomorrow - current
        )

    def rho(self) -> float:

        bump = 0.0001

        z = self._normal_draws()

        price_up = self._price_scenario(
            r=self.r + bump,
            z=z,
        )

        price_down = self._price_scenario(
            r=self.r - bump,
            z=z,
        )

        derivative = (
            price_up - price_down
        ) / (
            2.0 * bump
        )

        return float(
            derivative / 100.0
        )

    # -------------------------------------------------------------------------
    # CORRELATION SENSITIVITY
    # -------------------------------------------------------------------------

    def correlation_sensitivity(
        self,
        correlations: list[float] | np.ndarray,
    ) -> pd.DataFrame:
        """
        Applies a common off-diagonal correlation rho.

        Most useful for equally structured baskets.
        """

        results = []

        z = self._normal_draws()

        for rho in correlations:

            rho = float(rho)

            lower_bound = (
                -1.0
                / (self.n_assets - 1)
                if self.n_assets > 1
                else 0.0
            )

            if self.n_assets > 1 and not (
                lower_bound < rho < 1.0
            ):
                continue

            corr = np.full(
                (
                    self.n_assets,
                    self.n_assets,
                ),
                rho,
            )

            np.fill_diagonal(
                corr,
                1.0,
            )

            value = self._price_scenario(
                correlation_matrix=corr,
                z=z,
            )

            results.append({
                "correlation": rho,
                "price": value,
            })

        return pd.DataFrame(
            results
        )


