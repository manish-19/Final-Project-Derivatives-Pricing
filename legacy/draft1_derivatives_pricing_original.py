# Default shocks aligned with the project specification
# Spot shocks are percentages
SPOT_SHOCKS_PCT = [-10, -5, -1, 1, 5, 10]

# Volatility shocks are VOLATILITY POINTS:
# e.g. +5 means IV 25% -> 30%, not 25% -> 25.05%
VOL_SHOCKS_POINTS = [-10, -5, 5, 10]

# Interest-rate shocks are basis points
RATE_SHOCKS_BP = [-100, -50, 50, 100]

# Time decay is measured forward from the valuation date
TIME_SHOCKS_DAYS = [1, 7, 30]


class ScenarioShockAnalyzer:
    def __init__(self, model_builder, market_inputs, option_contract=None):
        self.model_builder = model_builder
        self.market_inputs = market_inputs
        self.option_contract = option_contract
        self.base_greeks = self._build(
            market_inputs,
            option_contract
        ).all_greeks()

    def _build(self, market_inputs, option_contract):
        return self.model_builder(
            market_inputs,
            option_contract
        )

    def _row(self, shock_type, shock_label, shock_value, greeks):
        base_price = self.base_greeks["price"]

        return {
            "shock_type": shock_type,
            "shock": shock_label,
            "shock_value": shock_value,
            "price": greeks["price"],
            "pnl": greeks["price"] - base_price,
            "pnl_pct": (
                (greeks["price"] - base_price)
                / base_price
                * 100.0
                if base_price
                else float("nan")
            ),
            "delta": greeks["delta"],
            "gamma": greeks["gamma"],
            "vega": greeks["vega"],
            "theta": greeks["theta"],
            "rho": greeks["rho"],
        }

    def spot_shocks(self, pct_moves=None):
        pct_moves = (
            pct_moves
            if pct_moves is not None
            else SPOT_SHOCKS_PCT
        )

        rows = []

        for pct in pct_moves:
            shocked_mi = MarketInputs(
                underlying_price=(
                    self.market_inputs.underlying_price
                    * (1 + pct / 100.0)
                ),
                risk_free_rate=self.market_inputs.risk_free_rate,
                dividend_yield=self.market_inputs.dividend_yield,
                valuation_date=self.market_inputs.valuation_date,
            )

            greeks = self._build(
                shocked_mi,
                self.option_contract
            ).all_greeks()

            rows.append(
                self._row(
                    "spot",
                    f"{pct:+d}%",
                    pct,
                    greeks
                )
            )

        return pd.DataFrame(rows)

    def vol_shocks(self, vol_point_moves=None):
        """
        Shock implied volatility by absolute volatility points.

        Example:
        IV = 25%
        +5 vol points -> 30%
        -5 vol points -> 20%
        """
        vol_point_moves = (
            vol_point_moves
            if vol_point_moves is not None
            else VOL_SHOCKS_POINTS
        )

        if (
            self.option_contract is None
            or self.option_contract.implied_volatility is None
        ):
            return pd.DataFrame()

        rows = []

        for points in vol_point_moves:

            # Convert volatility points to decimal volatility.
            # +5 vol points = +0.05
            shocked_vol = (
                self.option_contract.implied_volatility
                + points / 100.0
            )

            # Volatility cannot be zero or negative
            shocked_vol = max(
                shocked_vol,
                1e-6
            )

            shocked_oc = OptionContract(
                ticker=self.option_contract.ticker,
                option_type=self.option_contract.option_type,
                strike=self.option_contract.strike,
                expiry_date=self.option_contract.expiry_date,
                implied_volatility=shocked_vol,
            )

            greeks = self._build(
                self.market_inputs,
                shocked_oc
            ).all_greeks()

            rows.append(
                self._row(
                    "vol",
                    f"{points:+d} vol pts",
                    points,
                    greeks
                )
            )

        return pd.DataFrame(rows)

    def rate_shocks(self, bp_moves=None):
        bp_moves = (
            bp_moves
            if bp_moves is not None
            else RATE_SHOCKS_BP
        )

        rows = []

        for bp in bp_moves:
            shocked_rate = (
                self.market_inputs.risk_free_rate
                + bp / 10000.0
            )

            shocked_mi = MarketInputs(
                underlying_price=self.market_inputs.underlying_price,
                risk_free_rate=shocked_rate,
                dividend_yield=self.market_inputs.dividend_yield,
                valuation_date=self.market_inputs.valuation_date,
            )

            greeks = self._build(
                shocked_mi,
                self.option_contract
            ).all_greeks()

            rows.append(
                self._row(
                    "rate",
                    f"{bp:+d}bp",
                    bp,
                    greeks
                )
            )

        return pd.DataFrame(rows)

    def time_shocks(self, day_moves=None):
        day_moves = (
            day_moves
            if day_moves is not None
            else TIME_SHOCKS_DAYS
        )

        if self.option_contract is None:
            return pd.DataFrame()

        rows = []

        for days in day_moves:
            shocked_date = (
                self.market_inputs.valuation_date
                + timedelta(days=days)
            )

            # Keep valuation date strictly before expiry
            shocked_date = min(
                shocked_date,
                self.option_contract.expiry_date
                - timedelta(days=1)
            )

            shocked_mi = MarketInputs(
                underlying_price=self.market_inputs.underlying_price,
                risk_free_rate=self.market_inputs.risk_free_rate,
                dividend_yield=self.market_inputs.dividend_yield,
                valuation_date=shocked_date,
            )

            greeks = self._build(
                shocked_mi,
                self.option_contract
            ).all_greeks()

            rows.append(
                self._row(
                    "time",
                    f"+{days:d}d",
                    days,
                    greeks
                )
            )

        return pd.DataFrame(rows)

    def full_shock_table(self):
        frames = [
            self.spot_shocks(),
            self.rate_shocks(),
            self.time_shocks()
        ]

        if (
            self.option_contract is not None
            and self.option_contract.implied_volatility is not None
        ):
            frames.insert(
                1,
                self.vol_shocks()
            )

        base_row = self._row(
            "base",
            "0",
            0,
            self.base_greeks
        )

        return pd.concat(
            [
                pd.DataFrame([base_row]),
                *frames
            ],
            ignore_index=True
        )

