# PHASE 3E — SYNTHETIC OPTIONS ON GOLD FUTURES (BLACK-76)
#
# Fixes the original Black-76 problem: it was being fed AAPL equity options,
# which is mathematically redundant with BSM (F derived from S via
# F=S*exp((r-q)T) is exactly what BSM already does internally). Real
# options-on-futures data does not exist anywhere we have access to
# (confirmed earlier: yfinance's futures tickers all have empty .options
# chains; the lse-data package has no futures-options coverage either). So
# this section builds a SYNTHETIC options-on-gold-futures chain instead,
# calibrated against real data wherever real data exists:
#
#   - Spot proxy            -> real GLD (physically-backed gold ETF)
#   - Futures price          -> real GC=F (COMEX 100oz gold futures, front month)
#   - Net carry (y - u)      -> CALIBRATED from the real GLD/GC=F basis (not
#                               assumed), after converting GLD's per-share
#                               price into $/troy-oz terms via GLD's oz-per-
#                               share ratio (estimated from trailing price
#                               history, since the live disclosed ratio isn't
#                               available through any API we have access to)
#   - Volatility             -> realized, from real GC=F daily log returns
#   - Forward curve          -> synthesized via cost-of-carry, F(T) = S*exp((r-q)T),
#                               reusing Black76Model's own existing formula
#                               unmodified (its "dividend_yield" field is
#                               repurposed here as -(convenience yield - storage cost))
#   - Premiums, Greeks       -> generated by Black76Model itself (this file's
#                               existing, unmodified model)
#   - Bid/ask, open interest -> cosmetic synthesis only (no real market exists
#                               to draw these from)
#
# HONESTY CHECKS (read before using this as anything beyond a mechanics demo):
#   1. Real COMEX gold options (ticker OG) are AMERICAN-style. Black76Model
#      here is the closed-form EUROPEAN model, so this will not capture the
#      early-exercise premium real listed gold options carry.
#   2. The premiums are generated BY Black-76 itself, so this dataset can
#      never validate whether Black-76 matches real market prices -- it only
#      demonstrates the forward/carry/Greek mechanics are wired correctly,
#      using real spot, real futures, real rate, and real realized vol as the
#      only genuinely "real" inputs.
# =============================================================================

def run_phase3e_gold76_black76():
    """Synthetic options-on-gold-futures (Black-76) demo. Callable from main.

    Returns a dict with the synthetic chain, the near-ATM summary table,
    and the calibrated net-carry/volatility inputs used to build it.
    """
    import calendar as gold76_calendar
    import yfinance as yf

    print("\n" + "=" * 80)
    print("PHASE 3E — SYNTHETIC OPTIONS ON GOLD FUTURES (BLACK-76)")
    print("=" * 80)


    def gold76_front_month_expiry(valuation_date: date, min_days_out: int = 10) -> date:
        """
        Approximate the next active COMEX gold (GC) contract's last trading day.
        Active delivery months: Feb, Apr, Jun, Aug, Oct, Dec. Real GC contracts
        stop trading on the 3rd-to-last business day of the delivery month.
        `min_days_out` skips a contract about to expire, since a generic
        continuous futures ticker (like yfinance's GC=F) typically already
        reflects the next contract a bit before the literal expiry date.
        """
        active_months = [2, 4, 6, 8, 10, 12]
        candidates = []
        for year_offset in (0, 1):
            year = valuation_date.year + year_offset
            for month in active_months:
                last_calendar_day = gold76_calendar.monthrange(year, month)[1]
                probe = date(year, month, last_calendar_day)
                business_days_from_end = 0
                while True:
                    if probe.weekday() < 5:
                        business_days_from_end += 1
                        if business_days_from_end == 3:
                            break
                    probe -= timedelta(days=1)
                if probe > valuation_date + timedelta(days=min_days_out):
                    candidates.append(probe)
        return min(candidates)


    def gold76_forward_price(spot: float, r: float, q_net: float, T: float) -> float:
        """Cost-of-carry forward: F = S * exp((r - q_net) * T), q_net = convenience yield - storage cost."""
        return spot * np.exp((r - q_net) * T)


    gold76_valuation_date = date.today()

    print("\nCalibrating net carry from real GLD (spot proxy) vs. real GC=F (futures)...")

    gold76_gld_collector = YahooMarketDataCollector("GLD", manual_risk_free_rate=0.045, manual_dividend_yield=0.0)
    gold76_gc_collector = YahooMarketDataCollector("GC=F", manual_risk_free_rate=0.045, manual_dividend_yield=0.0)

    gold76_gld_spot = gold76_gld_collector.get_underlying_price()
    gold76_gc_price = gold76_gc_collector.get_underlying_price()
    gold76_r = gold76_gld_collector.get_risk_free_rate()

    # GLD's share price is NOT $/troy-oz -- it represents a fraction of an ounce
    # (originally ~0.1 oz at launch, slowly decaying due to the 0.40% expense
    # ratio). That fraction isn't available live through any API we have, so it's
    # estimated from the trailing GLD/GC=F price ratio, which is dominated by the
    # (near-constant, structural) oz-per-share ratio and only lightly noised by
    # the small day-to-day futures basis.
    gold76_scale_hist = yf.download(["GLD", "GC=F"], period="60d", auto_adjust=False, progress=False)["Close"].dropna()
    gold76_oz_per_share = float((gold76_scale_hist["GLD"] / gold76_scale_hist["GC=F"]).median())
    gold76_gld_spot_oz_equiv = gold76_gld_spot / gold76_oz_per_share

    gold76_front_expiry = gold76_front_month_expiry(gold76_valuation_date)
    gold76_T_front = (gold76_front_expiry - gold76_valuation_date).days / 365.0
