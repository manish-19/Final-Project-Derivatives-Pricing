class CRRBinomialTree(PricingModel):
    """Cox-Ross-Rubinstein binomial tree for American / European options."""

    def __init__(
        self,
        market_inputs: MarketInputs,
        option_contract: OptionContract,
        N: int = 500,
        american: bool = True,
    ) -> None:
        super().__init__(market_inputs, option_contract)
        self.S = float(market_inputs.underlying_price)
        self.K = float(option_contract.strike)
        self.r = float(market_inputs.risk_free_rate)
        self.q = float(market_inputs.dividend_yield)
        self.T = max((option_contract.expiry_date - market_inputs.valuation_date).days / 365.0, 1e-10)
        self.sigma = float(option_contract.implied_volatility) if option_contract.implied_volatility else 0.20
        self.N = int(N)
        self.american = bool(american)

        self.dt = self.T / self.N
        self.u = np.exp(self.sigma * np.sqrt(self.dt))
        self.d = 1.0 / self.u
        self.p = (np.exp((self.r - self.q) * self.dt) - self.d) / (self.u - self.d)
        self.disc = np.exp(-self.r * self.dt)

    def _build_tree(self) -> tuple[np.ndarray, np.ndarray]:
        N = self.N
        st = np.zeros((N + 1, N + 1))
        st[0, 0] = self.S
        for i in range(1, N + 1):
            st[i, 0] = st[i - 1, 0] * self.u
            for j in range(1, i + 1):
                st[i, j] = st[i - 1, j - 1] * self.d

        o = np.zeros((N + 1, N + 1))
        is_call = self.option_contract.option_type == "call"
        for j in range(N + 1):
            o[N, j] = max(st[N, j] - self.K, 0.0) if is_call else max(self.K - st[N, j], 0.0)

        for i in range(N - 1, -1, -1):
            for j in range(i + 1):
                cont = self.disc * (self.p * o[i + 1, j] + (1.0 - self.p) * o[i + 1, j + 1])
                if self.american:
                    ex = max(st[i, j] - self.K, 0.0) if is_call else max(self.K - st[i, j], 0.0)
                    o[i, j] = max(cont, ex)
                else:
                    o[i, j] = cont
        return st, o

    def price(self) -> float:
        _, o = self._build_tree()
        return float(o[0, 0])

    def delta(self) -> float:
        st, o = self._build_tree()
        return float((o[1, 0] - o[1, 1]) / (st[1, 0] - st[1, 1]))

    def gamma(self) -> float:
        st, o = self._build_tree()
        du = (o[2, 0] - o[2, 1]) / (st[2, 0] - st[2, 1])
        dd = (o[2, 1] - o[2, 2]) / (st[2, 1] - st[2, 2])
        return float((du - dd) / (0.5 * (st[2, 0] - st[2, 2])))

    def vega(self) -> float:
        b = 0.001
        orig = self.sigma
        self.sigma = orig + b
        self.u = np.exp(self.sigma * np.sqrt(self.dt))
        self.d = 1.0 / self.u
        self.p = (np.exp((self.r - self.q) * self.dt) - self.d) / (self.u - self.d)
        pu = self.price()

        self.sigma = orig - b
        self.u = np.exp(self.sigma * np.sqrt(self.dt))
        self.d = 1.0 / self.u
        self.p = (np.exp((self.r - self.q) * self.dt) - self.d) / (self.u - self.d)
        pd = self.price()

        self.sigma = orig
        self.u = np.exp(self.sigma * np.sqrt(self.dt))
        self.d = 1.0 / self.u
        self.p = (np.exp((self.r - self.q) * self.dt) - self.d) / (self.u - self.d)
        return float((pu - pd) / (2.0 * b * 100.0))

    def theta(self) -> float:
        _, o = self._build_tree()
        return float((o[2, 1] - o[0, 0]) / (2.0 * self.dt * 365.0))

    def rho(self) -> float:
        b = 0.0001
        orig = self.r
        self.r = orig + b
        self.disc = np.exp(-self.r * self.dt)
        self.p = (np.exp((self.r - self.q) * self.dt) - self.d) / (self.u - self.d)
        pu = self.price()

        self.r = orig - b
        self.disc = np.exp(-self.r * self.dt)
        self.p = (np.exp((self.r - self.q) * self.dt) - self.d) / (self.u - self.d)
        pd = self.price()

        self.r = orig
        self.disc = np.exp(-self.r * self.dt)
        self.p = (np.exp((self.r - self.q) * self.dt) - self.d) / (self.u - self.d)
        return float((pu - pd) / (2.0 * b * 100.0))

    def exercise_boundary(self, time_grid: list[float]) -> list[float]:
        """Critical stock price S*(T) at which early exercise becomes optimal, for each T in time_grid."""
        def price_at(S: float, T: float) -> float:
            mi = MarketInputs(S, self.market_inputs.risk_free_rate, self.market_inputs.dividend_yield,
                               self.market_inputs.valuation_date)
            oc = OptionContract(self.option_contract.ticker, self.option_contract.option_type, self.K,
                                 self.market_inputs.valuation_date + timedelta(days=max(int(round(T * 365.0)), 1)),
                                 self.sigma)
            return CRRBinomialTree(mi, oc, N=self.N, american=True).price()
        return _bisect_exercise_boundary(price_at, self.K, self.option_contract.option_type, time_grid)

class Black76Model(PricingModel):
    """Black-76 model for options on futures."""

    def __init__(self, market_inputs: MarketInputs, option_contract: OptionContract) -> None:
        super().__init__(market_inputs, option_contract)
        self.S = float(market_inputs.underlying_price)
        self.K = float(option_contract.strike)
        self.r = float(market_inputs.risk_free_rate)
        self.q = float(market_inputs.dividend_yield)
        self.T = max((option_contract.expiry_date - market_inputs.valuation_date).days / 365.0, 1e-10)
        self.sigma = float(option_contract.implied_volatility) if option_contract.implied_volatility else 0.20
        self.F = self.S * np.exp((self.r - self.q) * self.T)

        sT = np.sqrt(self.T)
        self.d1 = (np.log(self.F / self.K) + 0.5 * self.sigma ** 2 * self.T) / (self.sigma * sT)
        self.d2 = self.d1 - self.sigma * sT
        self._erT = np.exp(-self.r * self.T)
        self._nd1 = norm.pdf(self.d1)
        self._Nd1 = norm.cdf(self.d1)
        self._Nd2 = norm.cdf(self.d2)
        self._Nnd1 = norm.cdf(-self.d1)
        self._Nnd2 = norm.cdf(-self.d2)

    def price(self) -> float:
        if self.option_contract.option_type == "call":
            return self._erT * (self.F * self._Nd1 - self.K * self._Nd2)
        return self._erT * (self.K * self._Nnd2 - self.F * self._Nnd1)

    def delta(self) -> float:
        if self.option_contract.option_type == "call":
            return self._erT * self._Nd1
        return self._erT * (self._Nd1 - 1.0)

    def gamma(self) -> float:
        return self._erT * self._nd1 / (self.F * self.sigma * np.sqrt(self.T))

    def vega(self) -> float:
        return self.F * self._erT * self._nd1 * np.sqrt(self.T) / 100.0

    def theta(self) -> float:
        t1 = -self.F * self._erT * self._nd1 * self.sigma / (2.0 * np.sqrt(self.T))
        if self.option_contract.option_type == "call":
            return (t1 - self.r * self._erT * (self.F * self._Nd1 - self.K * self._Nd2)) / 365.0
        return (t1 + self.r * self._erT * (self.K * self._Nnd2 - self.F * self._Nnd1)) / 365.0

    def rho(self) -> float:
        """
        Rho per 1 percentage-point change in rates.

        Because F = S * exp((r-q)*T) is derived from spot, we must
        include the cost-of-carry sensitivity. This makes the result
        consistent with BSM rho.
        """
        if self.option_contract.option_type == "call":
            return self.K * self.T * self._erT * self._Nd2 / 100.0
        return -self.K * self.T * self._erT * self._Nnd2 / 100.0

